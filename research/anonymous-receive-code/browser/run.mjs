// Local real-browser benchmark. No RPC, production wallet or user material.
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import http from "node:http";
import {fileURLToPath} from "node:url";
import {createRequire} from "node:module";
import {execFile} from "node:child_process";
import {promisify} from "node:util";

assert.ok(process.argv[2],"Expected browser-jobs.json generated by the native research exporter");
const configFile=path.resolve(process.argv[2]),config=JSON.parse(fs.readFileSync(configFile,"utf8"));
const out=path.resolve(process.argv[3]??fs.mkdtempSync(path.join(os.tmpdir(),"deepfamily-browser-run-")));
fs.mkdirSync(out,{recursive:true});
const here=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(here,"../../..");
assert.ok(!out.startsWith(root+path.sep),"Results must stay outside the repository");
const require=createRequire(path.join(root,"frontend/package.json"));
const {chromium}=require("playwright-core");
const exec=promisify(execFile);
const selected=process.env.DEEPFAMILY_BROWSER_JOB;
const repeats=Number(process.env.DEEPFAMILY_BROWSER_REPEATS??"1");
assert.ok(Number.isInteger(repeats)&&repeats>0&&repeats<=2);
const timeoutMillis=Number(process.env.DEEPFAMILY_BROWSER_TIMEOUT_MS??"900000");
const maxRss=6*1024*1024*1024;
const jobs=config.jobs.filter(j=>!selected||j.name===selected);
assert.ok(jobs.length,"No selected jobs");
const files=new Map([
 ["/",path.join(here,"index.html")],["/worker.js",path.join(here,"worker.js")],
 ["/prover.wasm",config.wasmPath],["/wasm_exec.js",config.wasmExecPath],
]);
for(const job of jobs)for(const kind of ["r1cs","pk","vk","witness"]){
 assert.ok(fs.statSync(job[kind]).isFile());files.set("/artifact/"+encodeURIComponent(job.name)+"/"+kind,job[kind]);
}
const transfers=[];
const server=http.createServer((request,response)=>{
 const url=new URL(request.url,"http://127.0.0.1").pathname;
 response.setHeader("Cross-Origin-Opener-Policy","same-origin");
 response.setHeader("Cross-Origin-Embedder-Policy","require-corp");
 response.setHeader("Cache-Control","no-store");
 if(url==="/jobs"){response.setHeader("Content-Type","application/json");response.end(JSON.stringify({jobs:jobs.map(j=>({name:j.name}))}));return;}
 const file=files.get(url);
 if(!file){response.writeHead(404);response.end();return;}
 response.setHeader("Content-Type",file.endsWith(".wasm")?"application/wasm":file.endsWith(".js")?"text/javascript":file.endsWith(".html")?"text/html":"application/octet-stream");
 response.setHeader("Content-Length",fs.statSync(file).size);
 transfers.push({route:url,bytes:fs.statSync(file).size,at:Date.now()});
 fs.createReadStream(file).on("error",()=>response.destroy()).pipe(response);
});
await new Promise(resolve=>server.listen(0,"127.0.0.1",resolve));
const base="http://127.0.0.1:"+server.address().port;
const result={scope:"actual desktop Chrome Go/WASM proving in a Worker using synthetic precomputed full witnesses",createdAt:new Date().toISOString(),configFile,platform:process.platform,arch:process.arch,nodeVersion:process.version,hostMemoryBytes:os.totalmem(),cpuModel:os.cpus()[0]?.model,cpuCount:os.cpus().length,jobs:[],transfers,limitations:[
 "Desktop browser only; no physical phone measurements. Mobile viewport or user-agent emulation is not hardware testing.",
 "Loopback download measurements exclude production CDN/mobile bandwidth and cache conditions.",
 "Full synthetic witnesses and inner issuance proofs were prepared natively; this tests the outer prover, not identity/password/issuance UI.",
 "Sampled RSS sums process RSS, which can double-count shared pages; this is not exclusive physical memory.",
 "A 6GiB sampled RSS safety limit and configurable timeout stop an experiment; these are harness limits, not detected browser/phone limits.",
 "Local insecure development setup and small research tree capacities; not production keys or a release acceptance result.",
]};
let browserServer,browser;
async function memory(rootPid){
 const {stdout}=await exec("ps",["-axo","pid=,ppid=,rss="],{maxBuffer:4*1024*1024});
 const records=stdout.trim().split("\n").map(l=>l.trim().split(/\s+/).map(Number));
 const pids=new Set([rootPid]);let previous;
 do{previous=pids.size;for(const [pid,ppid]of records)if(pids.has(ppid))pids.add(pid);}while(previous!==pids.size);
 const processes=records.filter(([pid])=>pids.has(pid));
 return {at:Date.now(),rssSumBytes:processes.reduce((sum,row)=>sum+row[2]*1024,0),processCount:processes.length};
}
try{
 for(const job of jobs){
  const item={name:job.name,artifacts:Object.fromEntries(["r1cs","pk","vk","witness"].map(k=>[k,{bytes:fs.statSync(job[k]).size,file:job[k]}])),events:[],memorySamples:[]};
  result.jobs.push(item);let stop=false,sampling=false,timer;
  browserServer=await chromium.launchServer({executablePath:process.env.DEEPFAMILY_CHROME_PATH??"/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",headless:true,args:["--no-first-run","--no-default-browser-check"]});
  browser=await chromium.connect(browserServer.wsEndpoint());result.browserVersion=browser.version();
  const page=await browser.newPage();item.console=[];
  page.on("console",message=>{const value={type:message.type(),text:message.text().slice(0,12000)};item.console.push(value);if(item.console.length<=40)console.log(JSON.stringify({job:job.name,browserConsole:value}));});
  page.on("pageerror",error=>{item.pageError=String(error);});
  page.on("crash",()=>{item.pageCrashed=true;});
  await page.exposeFunction("researchEvent",event=>{
   item.events.push(event);
   if(event.phase)console.log(JSON.stringify({job:job.name,phase:event.phase,iteration:event.iteration,bytes:event.bytes,millis:event.millis,wallMillis:event.wallMillis,verified:event.verified}));
  });
  await page.goto(base);
  item.environment=await page.evaluate(()=>({crossOriginIsolated:window.crossOriginIsolated,isSecureContext:window.isSecureContext,hardwareConcurrency:navigator.hardwareConcurrency,deviceMemory:navigator.deviceMemory??null,userAgent:navigator.userAgent,sharedArrayBufferAvailable:typeof SharedArrayBuffer!=="undefined"}));
  await page.evaluate(()=>{const list=window.researchStatus.events;list.push=function(event){window.researchEvent(event);return Array.prototype.push.call(this,event);};});
  item.memorySamples.push(await memory(browserServer.process().pid));
  timer=setInterval(async()=>{
   if(sampling||stop)return;sampling=true;
   try{
    const sample=await memory(browserServer.process().pid);item.memorySamples.push(sample);
    if(sample.rssSumBytes>maxRss){item.harnessStop="sampled-rss-sum-exceeded-6GiB";stop=true;await browser.close();}
   }catch(error){item.samplingError=String(error);}finally{sampling=false;}
  },1000);
  const started=Date.now();
  await page.evaluate(({name,repeats})=>window.startResearch(name,repeats),{name:job.name,repeats});
  try{
   await page.waitForFunction(()=>window.researchStatus.done,null,{timeout:timeoutMillis});
   item.status=await page.evaluate(()=>window.researchStatus);
   item.result=item.status.result;delete item.status.events;
   item.completed=item.result.type==="result"&&item.result.proofs.every(p=>p.verified);
   if(item.completed){
    const expected=JSON.parse(fs.readFileSync(job.expectedPublic,"utf8"));
    for(const proof of item.result.proofs)assert.deepEqual(proof.publicSignals.map(String),expected.map(String));
    item.matchesExpectedPublicSignals=true;
   }
  }catch(error){item.error=String(error);item.completed=false;item.harnessStop??="timeout-or-browser-close";}
  finally{
   stop=true;clearInterval(timer);item.wallMillis=Date.now()-started;
   item.sampledPeakProcessRssSumBytes=Math.max(...item.memorySamples.map(s=>s.rssSumBytes));
   await browser.close().catch(()=>{});await browserServer.close().catch(()=>{});browser=null;browserServer=null;
   fs.writeFileSync(path.join(out,"results.json"),JSON.stringify(result,null,2)+"\n");
  }
  console.log(JSON.stringify({job:job.name,completed:item.completed,totalMillis:item.wallMillis,sampledPeakProcessRssSumBytes:item.sampledPeakProcessRssSumBytes,harnessStop:item.harnessStop}));
 }
}finally{
 await browser?.close().catch(()=>{});await browserServer?.close().catch(()=>{});
 await new Promise(resolve=>server.close(resolve));
 fs.writeFileSync(path.join(out,"results.json"),JSON.stringify(result,null,2)+"\n");
}
console.log(JSON.stringify({out,jobs:result.jobs.map(j=>({name:j.name,completed:j.completed}))}));
