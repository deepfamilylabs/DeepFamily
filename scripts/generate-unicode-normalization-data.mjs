#!/usr/bin/env node

import { createHash } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const UNICODE_VERSION = "17.0.0";
const SOURCES = Object.freeze([
  Object.freeze({
    name: "UnicodeData.txt",
    url: `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/UnicodeData.txt`,
    sha256: "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
  }),
  Object.freeze({
    name: "DerivedNormalizationProps.txt",
    url: `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/DerivedNormalizationProps.txt`,
    sha256: "71fd6a206a2c0cdd41feb6b7f656aa31091db45e9cedc926985d718397f9e488",
  }),
]);
const NORMALIZATION_TEST_SOURCE = Object.freeze({
  name: "NormalizationTest.txt",
  url: `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/NormalizationTest.txt`,
  sha256: "5019ffd530751a741900c849c0e010332f142a3612234639bd200b82138a87db",
});
const UNICODE_LICENSE_SHA256 = "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96";

const scriptPath = fileURLToPath(import.meta.url);
const repositoryRoot = path.resolve(path.dirname(scriptPath), "..");
const outputPath = path.join(
  repositoryRoot,
  "packages",
  "protocol-core",
  "unicode-normalization-data.js",
);
const licensePath = path.join(repositoryRoot, "packages", "protocol-core", "UNICODE-LICENSE.txt");

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

async function fetchPinnedSource(source) {
  const response = await fetch(source.url, {
    headers: { "user-agent": "DeepFamily Unicode normalization data generator" },
    redirect: "follow",
  });
  if (!response.ok) {
    throw new Error(`${source.name} download failed with HTTP ${response.status}`);
  }
  const bytes = Buffer.from(await response.arrayBuffer());
  const actualSha256 = sha256(bytes);
  if (actualSha256 !== source.sha256) {
    throw new Error(
      `${source.name} SHA-256 mismatch: expected ${source.sha256}, got ${actualSha256}`,
    );
  }
  return bytes.toString("utf8");
}

function parseFullCompositionExclusions(source) {
  const exclusions = new Set();
  for (const rawLine of source.split(/\r?\n/u)) {
    const line = rawLine.replace(/#.*/u, "").trim();
    if (!line) continue;
    const [rangeText, property] = line.split(";").map((value) => value.trim());
    if (property !== "Full_Composition_Exclusion") continue;
    const [startText, endText = startText] = rangeText.split("..");
    const start = Number.parseInt(startText, 16);
    const end = Number.parseInt(endText, 16);
    for (let codePoint = start; codePoint <= end; codePoint += 1) exclusions.add(codePoint);
  }
  return exclusions;
}

function parseUnicodeData(source, fullCompositionExclusions) {
  const combiningClasses = [];
  const decompositions = [];
  const compositions = [];

  for (const line of source.split(/\r?\n/u)) {
    if (!line) continue;
    const fields = line.split(";");
    const codePoint = Number.parseInt(fields[0], 16);
    const combiningClass = Number.parseInt(fields[3], 10);
    const decompositionText = fields[5];
    if (combiningClass !== 0) combiningClasses.push([codePoint, combiningClass]);
    if (!decompositionText) continue;

    const compatibility = decompositionText.startsWith("<");
    const mappingText = decompositionText.replace(/^<[^>]+>\s*/u, "");
    const mapping = mappingText.split(/\s+/u).map((value) => Number.parseInt(value, 16));
    decompositions.push([codePoint, mapping]);

    if (
      !compatibility &&
      mapping.length === 2 &&
      combiningClass === 0 &&
      !fullCompositionExclusions.has(codePoint)
    ) {
      compositions.push([mapping[0], mapping[1], codePoint]);
    }
  }

  return { combiningClasses, decompositions, compositions };
}

const serializeRows = (rows) => rows.map((row) => `  ${JSON.stringify(row)},`).join("\n");

const formatUnicodeLicenseComment = (licenseText) =>
  `/*! @license Unicode-3.0\n${licenseText
    .trimEnd()
    .split(/\r?\n/u)
    .map((line) => (line === "" ? " *" : ` * ${line}`))
    .join("\n")}\n */\n`;

function generateModule({ combiningClasses, decompositions, compositions, unicodeLicense }) {
  const sourceSummary = SOURCES.map(
    (source) => `// - ${source.url} (SHA-256 ${source.sha256})`,
  ).join("\n");
  return (
    `// Generated by scripts/generate-unicode-normalization-data.mjs. Do not edit.\n` +
    formatUnicodeLicenseComment(unicodeLicense) +
    `// Unicode ${UNICODE_VERSION} normalization data, pinned to official UCD bytes:\n` +
    `${sourceSummary}\n\n` +
    `export const UNICODE_NORMALIZATION_VERSION = "${UNICODE_VERSION}";\n\n` +
    `// prettier-ignore\n` +
    `export const UNICODE_COMBINING_CLASS_ENTRIES = [\n${serializeRows(combiningClasses)}\n];\n\n` +
    `// prettier-ignore\n` +
    `export const UNICODE_COMPATIBILITY_DECOMPOSITION_ENTRIES = [\n${serializeRows(decompositions)}\n];\n\n` +
    `// prettier-ignore\n` +
    `export const UNICODE_CANONICAL_COMPOSITION_ENTRIES = [\n${serializeRows(compositions)}\n];\n`
  );
}

const parseCodePointSequence = (value) =>
  value.trim() === ""
    ? ""
    : String.fromCodePoint(
        ...value
          .trim()
          .split(/\s+/u)
          .map((codePoint) => Number.parseInt(codePoint, 16)),
      );

async function verifyNormalizationConformance(source) {
  const { normalizeUnicodeNfkc, normalizeUnicodeNfkd } =
    await import("../packages/protocol-core/unicode-normalization.js");
  const part1CodePoints = new Set();
  let currentPart = null;
  let records = 0;
  let assertions = 0;

  for (const rawLine of source.split(/\r?\n/u)) {
    const trimmed = rawLine.trim();
    const partMatch = /^@Part(\d+)\b/u.exec(trimmed);
    if (partMatch) {
      currentPart = Number.parseInt(partMatch[1], 10);
      continue;
    }
    const line = rawLine.replace(/#.*/u, "").trim();
    if (!line || line.startsWith("@")) continue;
    const columns = line.split(";").slice(0, 5).map(parseCodePointSequence);
    if (columns.length !== 5) {
      throw new Error(`Malformed ${NORMALIZATION_TEST_SOURCE.name} record: ${rawLine}`);
    }
    const [c1, c2, c3, c4, c5] = columns;
    if (currentPart === 1 && [...c1].length === 1) part1CodePoints.add(c1.codePointAt(0));

    for (const input of [c1, c2, c3, c4, c5]) {
      if (normalizeUnicodeNfkc(input) !== c4) {
        throw new Error(`Unicode ${UNICODE_VERSION} NFKC conformance failed at record ${records}`);
      }
      if (normalizeUnicodeNfkd(input) !== c5) {
        throw new Error(`Unicode ${UNICODE_VERSION} NFKD conformance failed at record ${records}`);
      }
      assertions += 2;
    }
    records += 1;
  }

  // UAX #15's second conformance clause requires every scalar not listed in
  // the character-by-character Part 1 table to normalize to itself.
  let unlistedScalars = 0;
  for (let codePoint = 0; codePoint <= 0x10_ffff; codePoint += 1) {
    if (codePoint >= 0xd800 && codePoint <= 0xdfff) continue;
    if (part1CodePoints.has(codePoint)) continue;
    const value = String.fromCodePoint(codePoint);
    if (normalizeUnicodeNfkc(value) !== value || normalizeUnicodeNfkd(value) !== value) {
      throw new Error(
        `Unicode ${UNICODE_VERSION} unlisted-scalar conformance failed at U+${codePoint
          .toString(16)
          .toUpperCase()
          .padStart(4, "0")}`,
      );
    }
    assertions += 2;
    unlistedScalars += 1;
  }
  return { records, unlistedScalars, assertions };
}

async function main(argv = process.argv.slice(2)) {
  if (argv.length > 1 || (argv.length === 1 && argv[0] !== "--check")) {
    throw new Error("Usage: node scripts/generate-unicode-normalization-data.mjs [--check]");
  }
  const [unicodeData, derivedNormalizationProperties] = await Promise.all(
    SOURCES.map(fetchPinnedSource),
  );
  const unicodeLicense = await fs.readFile(licensePath, "utf8");
  if (sha256(Buffer.from(unicodeLicense, "utf8")) !== UNICODE_LICENSE_SHA256) {
    throw new Error("UNICODE-LICENSE.txt does not match the reviewed Unicode-3.0 notice");
  }
  const generated = generateModule({
    ...parseUnicodeData(
      unicodeData,
      parseFullCompositionExclusions(derivedNormalizationProperties),
    ),
    unicodeLicense,
  });

  if (argv[0] === "--check") {
    const current = await fs.readFile(outputPath, "utf8");
    if (current !== generated) throw new Error("Generated Unicode normalization data is stale");
    const normalizationTest = await fetchPinnedSource(NORMALIZATION_TEST_SOURCE);
    const conformance = await verifyNormalizationConformance(normalizationTest);
    console.log(
      `Unicode ${UNICODE_VERSION} normalization conformance verified: ` +
        `${conformance.records} records, ${conformance.unlistedScalars} unlisted scalars, ` +
        `${conformance.assertions} assertions`,
    );
  } else {
    const temporaryPath = `${outputPath}.tmp`;
    await fs.writeFile(temporaryPath, generated, { encoding: "utf8", mode: 0o644 });
    await fs.rename(temporaryPath, outputPath);
  }
  console.log(
    `Unicode ${UNICODE_VERSION} normalization data ${argv[0] === "--check" ? "verified" : "generated"}: ` +
      `${sha256(Buffer.from(generated, "utf8"))}`,
  );
}

if (path.resolve(process.argv[1] ?? "") === scriptPath) {
  main().catch((error) => {
    console.error(`[unicode-normalization-data] ${error.message}`);
    process.exitCode = 1;
  });
}
